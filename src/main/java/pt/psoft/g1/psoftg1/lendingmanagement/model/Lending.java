package pt.psoft.g1.psoftg1.lendingmanagement.model;

import jakarta.persistence.*;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import lombok.Getter;
import org.hibernate.StaleObjectStateException;
import pt.psoft.g1.psoftg1.bookmanagement.model.Book;
import pt.psoft.g1.psoftg1.readermanagement.model.ReaderDetails;

import java.time.LocalDate;
import java.time.temporal.ChronoUnit;
import java.util.Objects;
import java.util.Optional;

/**
 * The {@code Lending} class associates a {@code Reader} and a {@code Book}.
 * <p>It stores the date it was registered, the date it is supposed to
 * be returned, and the date it actually was returned.
 * It also stores an optional reader {@code commentary} (submitted at the time of the return) and
 * the {@code Fine}, if applicable.
 * <p>It is identified in the system by an auto-generated {@code id}, and has a unique-constrained
 * natural key ({@code LendingNumber}) with its own business rules.
 * @author  rmfranca*/
@Entity
@Table(uniqueConstraints = {
        @UniqueConstraint(columnNames={"LENDING_NUMBER"})})
public class Lending {

    /**
     * Database primary key. Since this field is autogenerated by the database there
     * is not setId() method.
     * <p>
     * Since this field is an implementation detail that does not matter to the
     * domain, there is no getId() nor setId() method as this field must not be
     * exposed.
     * @author pgsousa
     */
    @Id
    @GeneratedValue(strategy = GenerationType.AUTO)
    private Long pk;

    /**
     * Natural key, which is not in use as it has its own business rules.
     * <p>
     * Composed of {@code int year}, {@code int sequencial} and {@code String lendingNumber}. The string is
     * constructed based on the values of {@code year} and {@code sequencial}.
     */
    private LendingNumber lendingNumber;

    /**
     * {@code Book} associated with this {@code Lending}.
     * */
    @NotNull
    @Getter
    @ManyToOne(fetch=FetchType.EAGER, optional = false)
    private Book book;

    /**
     * {@code Reader} associated with this {@code Lending}.
     **/
    @NotNull
    @Getter
    @ManyToOne(fetch=FetchType.EAGER, optional = false)
    private ReaderDetails readerDetails;

    /**
     * Date of this {@code Lending}'s creation.
     * */
    @NotNull
    @Column(nullable = false, updatable = false)
    @Temporal(TemporalType.DATE)
    @Getter
    private LocalDate startDate;

    /**
     * Date this {@code Lending} is to be returned.
     * */
    @NotNull
    @Column(nullable = false)
    @Temporal(TemporalType.DATE)
    @Getter
    private LocalDate limitDate;

    /**
     * Date this {@code Lending} is actually returned. This field is initialized as {@code null}
     * as the lending can never begin with the book already returned. The {@code null} value is used to
     * check if a book has been returned.
     * */
    @Temporal(TemporalType.DATE)
    @Getter
    private LocalDate returnedDate;

    // optimistic-lock
    /**
     * Version of the object, to handle concurrency of accesses.
     * */
    @Version
    @Getter
    private long version;

    /**
     * Optional commentary written by a reader when the book is returned.
     * This field is initialized as null as the lending can never begin with the book already returned
     * */
    @Size(min = 0, max = 1024)
    @Column(length = 1024)
    private String commentary = null;

    @Getter
    private int fineValuePerDayInCents;

    // Counted so Standard can enforce MaxRenewals; the column default keeps rows created before renewals existed valid.
    @Getter
    @Column(nullable = false, columnDefinition = "integer default 0")
    private int renewals;


    /**
     * Constructs a new {@code Lending} object to be persisted in the database.
     * <p>
     * Sets {@code startDate} as {@code today}, and {@code limitDate} as {@code today} plus the
     * number of days a reader can take to return the book.
     *
     * @param       book {@code Book} object, which should be retrieved from the database.
     * @param       readerDetails {@code Reader} object, which should be retrieved from the database.
     * @param       seq sequential number, which should be obtained from the year's count on the database.
     * @param       today reference date, supplied by the caller so the entity never reads the system clock.
     * @throws      NullPointerException if any of the arguments is {@code null}
     * */
    public Lending(Book book, ReaderDetails readerDetails, int seq, int lendingDuration, int fineValuePerDayInCents, LocalDate today){
        try {
            this.book = Objects.requireNonNull(book);
            this.readerDetails = Objects.requireNonNull(readerDetails);
        }catch (NullPointerException e){
            throw new IllegalArgumentException("Null objects passed to lending");
        }
        // Year comes from the supplied date, not the system clock, so lending numbers are reproducible in tests.
        this.lendingNumber = new LendingNumber(today.getYear(), seq);
        // Dates derive from the caller's reference date so overdue rules can be tested at fixed days (QAS11).
        this.startDate = today;
        this.limitDate = today.plusDays(lendingDuration);
        this.returnedDate = null;
        this.fineValuePerDayInCents = fineValuePerDayInCents;
    }

    /**
     * <p>Sets {@code commentary} and {@code today} as {@code returnedDate}.
     * <p>If {@code returnedDate} is after {@code limitDate}, fine is applied with corresponding value.
     *
     * @param       desiredVersion to prevent editing a stale object.
     * @param       commentary written by a reader.
     * @param       today reference date, supplied by the caller.
     * @throws      StaleObjectStateException if object was already modified by another user.
     * @throws      IllegalArgumentException  if {@code returnedDate} already has a value.
     */
    public void setReturned(final long desiredVersion, final String commentary, final LocalDate today){

        if (this.returnedDate != null)
            throw new IllegalArgumentException("book has already been returned!");

        // check current version
        if (this.version != desiredVersion)
            throw new StaleObjectStateException("Object was already modified by another user", this.pk);

        if(commentary != null)
            this.commentary = commentary;

        // The return date is supplied, not read from the clock, so late returns can be tested at fixed days.
        this.returnedDate = today;
    }

    /**
     * Extends the limit date by {@code extensionDays}. The policy decides whether and by how much;
     * the entity only guards its own invariants (CON-LP-1).
     *
     * @throws      StaleObjectStateException if object was already modified by another user.
     * @throws      IllegalArgumentException  if the lending was returned, is overdue at {@code today}, or the extension is not positive.
     */
    public void renew(final long desiredVersion, final int extensionDays, final LocalDate today){
        // Same guard order as setReturned: state first, then the optimistic-lock version.
        if (this.returnedDate != null)
            throw new IllegalArgumentException("A returned lending cannot be renewed");

        if (this.version != desiredVersion)
            throw new StaleObjectStateException("Object was already modified by another user", this.pk);

        // Overdue is judged at the supplied date so the rule is testable at fixed days; due today is still renewable.
        if (getDaysDelayed(today) > 0)
            throw new IllegalArgumentException("An overdue lending cannot be renewed");

        if (extensionDays <= 0)
            throw new IllegalArgumentException("The extension must be a positive number of days");

        this.limitDate = this.limitDate.plusDays(extensionDays);
        this.renewals++;
    }

    /**
     * <p>Returns the number of days that the lending is/was past its due date</p>
     * @param       today reference date, used when the book has not been returned.
     * @return      If the book was returned on time, or there is still time for it be returned, returns 0.
     * If the book has been returned with delay, returns the number of days of delay.
     * If the book has not been returned, returns the number of days
     * past its limit date.
     */
    public int getDaysDelayed(final LocalDate today){
        // Takes "today" as a parameter: the old no-arg version read the system clock, so results changed with the run date.
        if(this.returnedDate != null) {
            return Math.max((int) ChronoUnit.DAYS.between(this.limitDate, this.returnedDate), 0);
        }else{
            return Math.max((int) ChronoUnit.DAYS.between(this.limitDate, today), 0);
        }
    }

    public Optional<Integer> getDaysUntilReturn(final LocalDate today) {
        // Computed on demand: the former @Transient fields cached values calculated with the real clock.
        int daysUntilReturn = (int) ChronoUnit.DAYS.between(today, this.limitDate);
        if(this.returnedDate != null || daysUntilReturn < 0){
            return Optional.empty();
        }
        return Optional.of(daysUntilReturn);
    }

    public Optional<Integer> getDaysOverdue(final LocalDate today) {
        int days = getDaysDelayed(today);
        return days > 0 ? Optional.of(days) : Optional.empty();
    }

    public Optional<Integer> getFineValueInCents(final LocalDate today) {
        Optional<Integer> fineValueInCents = Optional.empty();
        int days = getDaysDelayed(today);
        if(days > 0){
            fineValueInCents = Optional.of(fineValuePerDayInCents * days);
        }
        return fineValueInCents;
    }

    public String getTitle(){
        return this.book.getTitle().toString();
    }

    public String getLendingNumber() {
        return this.lendingNumber.toString();
    }


    /**Protected empty constructor for ORM only.*/
    protected Lending() {}

    /**Factory method meant to be only used in bootstrapping.*/
    public static Lending newBootstrappingLending(Book book,
                                    ReaderDetails readerDetails,
                                    int year,
                                    int seq,
                                    LocalDate startDate,
                                    LocalDate returnedDate,
                                    int lendingDuration,
                                    int fineValuePerDayInCents){
        Lending lending = new Lending();

        try {
            lending.book = Objects.requireNonNull(book);
            lending.readerDetails = Objects.requireNonNull(readerDetails);
        }catch (NullPointerException e){
            throw new IllegalArgumentException("Null objects passed to lending");
        }
        lending.lendingNumber = new LendingNumber(year, seq);
        lending.startDate = startDate;
        lending.limitDate = startDate.plusDays(lendingDuration);
        lending.fineValuePerDayInCents = fineValuePerDayInCents;
        lending.returnedDate = returnedDate;
        return lending;

    }
}
